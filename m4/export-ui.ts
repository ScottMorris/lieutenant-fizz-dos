import { readFileSync, writeSync } from 'node:fs';

const GAME = process.env.FIZZ_GAME ?? new URL('../../../liminal-hq/lieutenant-fizz', import.meta.url).pathname; // the main game's checkout; FIZZ_GAME overrides
const { RAW, EXTRA } = await import(`${GAME}/packages/engine/src/font/fizz-glyphs.ts`);
const { LEVELS, SIGNS, DIALOGUE } = await import(`${GAME}/episodes/episode-1/src/story.ts`);
const { EGA } = await import(`${GAME}/packages/engine/src/palette.ts`);
const { TITLE_CARD } = await import(`${GAME}/episodes/episode-1/src/title-card.ts`);

const wasm = readFileSync(`${GAME}/episodes/episode-1/src/wasm/sim.wasm`);
const { instance } = await WebAssembly.instantiate(wasm, {});
const x = instance.exports as unknown as {
  memory: WebAssembly.Memory;
  table_len(t: number): number;
  name_ptr(t: number, i: number): number;
  name_len(t: number, i: number): number;
  caption_colour(i: number): number;
};
const table = (t: number) =>
  Array.from({ length: x.table_len(t) }, (_, i) =>
    new TextDecoder().decode(new Uint8Array(x.memory.buffer, x.name_ptr(t, i), x.name_len(t, i))),
  );

// ---- the font: every single-character glyph, as rows of bits with the leftmost pixel in the highest bit ----
const glyphs = new Map<number, { w: number; rows: number[] }>();
for (const [key, grid] of Object.entries({ ...RAW, ...EXTRA }) as [string, string][]) {
  const chars = Array.from(key);
  if (chars.length !== 1) continue;
  const rows = grid.split('/');
  const w = Math.max(...rows.map((r) => r.length));
  if (w > 16) continue;
  glyphs.set(chars[0].codePointAt(0)!, {
    w,
    rows: rows.map((r) => [...r.padEnd(w, '.')].reduce((bits, c) => (bits << 1) | (c === '#' ? 1 : 0), 0)),
  });
}

// ---- strings, with the few characters the font lacks swapped for plain ones ----
const swaps: Record<string, string> = { '“': '"', '”': '"', '‘': "'", '’': "'", '—': '-', '–': '-', '…': '...', '·': '-' };
const missing = new Set<string>();
const clean = (s: string) =>
  Array.from(s)
    .map((c) => {
      if (glyphs.has(c.codePointAt(0)!) || c === ' ') return c;
      if (swaps[c]) return swaps[c];
      missing.add(c);
      return '?';
    })
    .join('');
const rs = (s: string) => JSON.stringify(clean(s));
const list = (items: string[]) => `[${items.map(rs).join(', ')}]`;

const ega = Object.values(EGA) as string[];
const egaIndex = (rgb: number) => {
  const hex = `#${rgb.toString(16).padStart(6, '0')}`;
  const i = ega.indexOf(hex);
  return i < 0 ? 15 : i;
};
const captions = table(1).map((text, i) => {
  const colour = x.caption_colour(i);
  return `(${rs(text)}, ${colour === 0 ? 255 : egaIndex(colour)})`;
});
const levels = LEVELS as { name: string; blurb: string; cleared: string }[];
const dialogue = (lines: [string, string][]) => `&[${lines.map(([who, text]) => `(${rs(who)}, ${rs(text)})`).join(', ')}]`;

const out: string[] = [];
out.push('// @generated by m4/export-ui.ts from the game\'s font and strings. Do not edit.');
out.push('');
out.push('/// One glyph: its width and its rows from the top of a capital letter, the leftmost pixel in the highest bit.');
out.push('pub struct Glyph {');
out.push('    pub cp: u32,');
out.push('    pub w: u8,');
out.push('    pub rows: &\'static [u16],');
out.push('}');
out.push('');
out.push('pub static FONT: &[Glyph] = &[');
for (const [cp, g] of [...glyphs.entries()].sort((a, b) => a[0] - b[0]))
  out.push(`    Glyph { cp: ${cp}, w: ${g.w}, rows: &[${g.rows.join(', ')}] },`);
out.push('];');
out.push('');
out.push(`pub static LEVEL_NAMES: [&str; ${levels.length}] = ${list(levels.map((l) => l.name))};`);
out.push(`pub static LEVEL_BLURBS: [&str; ${levels.length}] = ${list(levels.map((l) => l.blurb))};`);
out.push(`pub static LEVEL_CLEARED: [&str; ${levels.length}] = ${list(levels.map((l) => l.cleared))};`);
out.push(`pub static SIGNS: [&str; ${SIGNS.length}] = ${list(SIGNS)};`);
out.push(`/// The sim's caption words with the colour of each as an EGA colour 0..15 (255 for none).`);
out.push(`pub static CAPTIONS: [(&str, u8); ${captions.length}] = [${captions.join(', ')}];`);
const toasts = table(2);
out.push(`pub static TOASTS: [&str; ${toasts.length}] = ${list(toasts)};`);
out.push(`pub static TITLE_KICKER: &str = ${rs(TITLE_CARD.kicker)};`);
out.push(`pub static TITLE_WORDS: &str = ${rs(TITLE_CARD.words.join(' '))};`);
out.push(`pub static TITLE_LINE: &str = ${rs(TITLE_CARD.line)};`);
out.push(`pub static BOSS_INTRO: &[(&str, &str)] = ${dialogue(DIALOGUE.bossIntro)};`);
out.push(`pub static BOSS_DEFEATED: &[(&str, &str)] = ${dialogue(DIALOGUE.bossDefeated)};`);
writeSync(1, out.join('\n') + '\n');
console.error(`${glyphs.size} glyphs; ${levels.length} levels, ${captions.length} captions, ${toasts.length} toasts; characters the font lacks: ${[...missing].join(' ') || 'none'}`);
